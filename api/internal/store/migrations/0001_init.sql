-- Calor schema v1 for PostgreSQL (ported from SQLite schema versions 1 and 2).
--
-- Times are bigint unix milliseconds, the unit of the wire format and of every
-- API field; bucketing by local hour/day with an arbitrary tz offset is integer
-- arithmetic on them. Text columns use the "C" collation so ordering and
-- grouping are byte-wise like SQLite's BINARY collation, whatever the
-- database locale.

CREATE TABLE sites (
	id         text COLLATE "C" PRIMARY KEY,
	name       text NOT NULL,
	domain     text COLLATE "C" NOT NULL,
	created_at bigint NOT NULL
);

-- Raw events, range-partitioned by month on ts (UTC). Partitions are created
-- on demand by the store (events_yYYYYmMM) so there is no default partition;
-- retention drops whole months and deletes the remainder in chunks.
CREATE TABLE events (
	id             bigint GENERATED BY DEFAULT AS IDENTITY,
	site_id        text COLLATE "C" NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
	type           text COLLATE "C" NOT NULL,
	page_url       text COLLATE "C" NOT NULL,
	session_id     text COLLATE "C" NOT NULL,
	pageview_id    text COLLATE "C" NOT NULL DEFAULT '',
	ts             bigint NOT NULL,
	x              double precision,
	y              double precision,
	viewport_w     integer NOT NULL DEFAULT 0,
	viewport_h     integer NOT NULL DEFAULT 0,
	doc_w          integer NOT NULL DEFAULT 0,
	doc_h          integer NOT NULL DEFAULT 0,
	selector       text COLLATE "C" NOT NULL DEFAULT '',
	el_tag         text COLLATE "C" NOT NULL DEFAULT '',
	el_id          text COLLATE "C" NOT NULL DEFAULT '',
	el_classes     text COLLATE "C" NOT NULL DEFAULT '',
	el_text        text COLLATE "C" NOT NULL DEFAULT '',
	el_label       text COLLATE "C" NOT NULL DEFAULT '',
	el_component   text COLLATE "C" NOT NULL DEFAULT '',
	rage           boolean NOT NULL DEFAULT false,
	dead           boolean NOT NULL DEFAULT false,
	target_url     text COLLATE "C" NOT NULL DEFAULT '',
	nav_kind       text COLLATE "C" NOT NULL DEFAULT '',
	referrer       text COLLATE "C" NOT NULL DEFAULT '',
	redirect_count integer NOT NULL DEFAULT 0,
	scroll_depth   double precision,
	duration_ms    integer NOT NULL DEFAULT 0,
	received_at    bigint NOT NULL,
	PRIMARY KEY (id, ts)
) PARTITION BY RANGE (ts);

CREATE INDEX idx_events_site_type_ts ON events (site_id, type, ts);
CREATE INDEX idx_events_site_page_type_ts ON events (site_id, page_url, type, ts);
CREATE INDEX idx_events_site_session_ts ON events (site_id, session_id, ts);
CREATE INDEX idx_events_pageview ON events (pageview_id);
-- Tiny block-range index for the retention delete of the boundary month.
CREATE INDEX idx_events_ts_brin ON events USING brin (ts);

-- Clicks pre-binned per hour into a fixed 200x800 document-relative grid.
-- Kept forever (retention only prunes raw events).
CREATE TABLE heatmap_rollup (
	site_id  text COLLATE "C" NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
	page_url text COLLATE "C" NOT NULL,
	type     text COLLATE "C" NOT NULL,
	device   text COLLATE "C" NOT NULL,
	hour     integer NOT NULL,
	gx       smallint NOT NULL,
	gy       smallint NOT NULL,
	n        integer NOT NULL,
	PRIMARY KEY (site_id, page_url, type, device, hour, gx, gy)
);

CREATE TABLE screenshots (
	site_id      text COLLATE "C" NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
	page_url     text COLLATE "C" NOT NULL,
	content_type text NOT NULL,
	data         bytea NOT NULL,
	width        integer NOT NULL DEFAULT 0,
	height       integer NOT NULL DEFAULT 0,
	updated_at   bigint NOT NULL,
	PRIMARY KEY (site_id, page_url)
);
-- Images are already compressed: store them out of line without pglz.
ALTER TABLE screenshots ALTER COLUMN data SET STORAGE EXTERNAL;

CREATE TABLE components (
	id           text COLLATE "C" PRIMARY KEY,
	site_id      text COLLATE "C" NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
	name         text COLLATE "C" NOT NULL,
	selector     text NOT NULL DEFAULT '',
	attr_name    text COLLATE "C" NOT NULL DEFAULT '',
	attr_value   text COLLATE "C" NOT NULL DEFAULT '',
	page_pattern text NOT NULL DEFAULT '',
	created_at   bigint NOT NULL,
	updated_at   bigint NOT NULL
);
CREATE INDEX idx_components_site ON components (site_id, name);

-- Click -> component junction, keyed by component then time so a
-- component-scoped query is one index range. Partitioned like events (same
-- months, same names with an event_components_ prefix) so retention drops
-- both together. No foreign keys: deletes are chunked instead of cascading.
CREATE TABLE event_components (
	component_id text COLLATE "C" NOT NULL,
	ts           bigint NOT NULL,
	event_id     bigint NOT NULL,
	PRIMARY KEY (component_id, ts, event_id)
) PARTITION BY RANGE (ts);
